int udev_add_unions_info(void)
{
	struct udev_hw_info hw_info = {0};

	hw_info.valid = HW_VALID;
	hw_info.chip_type = MAMI_KERN_TYPE_UNIONS;

	hw_info.mem_die_bitmap = ((0x1 << UDEV_DIE0) | (0x1 << UDEV_DIE1));
	hw_info.reg_die_bitmap = ((0x1 << UDEV_DIE0) | (0x1 << UDEV_DIE1));

	hw_info.addr_mem[UDEV_DIE0].addr_list = unions_mem_list_die0;
	hw_info.addr_mem[UDEV_DIE0].addr_num = ARRAY_SIZE(unions_mem_list_die0);
	hw_info.addr_mem[UDEV_DIE1].addr_list = unions_mem_list_die1;
	hw_info.addr_mem[UDEV_DIE1].addr_num = ARRAY_SIZE(unions_mem_list_die1);
	hw_info.addr_reg[UDEV_DIE0].addr_list = unions_reg_list_die0;
	hw_info.addr_reg[UDEV_DIE0].addr_num = ARRAY_SIZE(unions_reg_list_die0);
	hw_info.addr_reg[UDEV_DIE1].addr_list = unions_reg_list_die1;
	hw_info.addr_reg[UDEV_DIE1].addr_num = ARRAY_SIZE(unions_reg_list_die1);

	hw_info.key_value_list = unions_key_value_list;
	hw_info.key_value_num = ARRAY_SIZE(unions_key_value_list);
	hw_info.hsec_mem_list = hsec_mem_list;
	hw_info.hsec_mem_num = ARRAY_SIZE(hsec_mem_list);
	hw_info.init_win_axi = unions_init_win_axi;
	hw_info.init_win_axi_num = ARRAY_SIZE(unions_init_win_axi);
	return udev_add_hw_info(MAMI_KERN_TYPE_UNIONS, &hw_info);
}
DECLARE_FEATURE_AUTO_INIT(udev_add_unions_info, FEATURE_LOADER_STAGE_5);

